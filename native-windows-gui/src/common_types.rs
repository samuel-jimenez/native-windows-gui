/**
    Text align constant on the horizontal axis
*/
#[derive(PartialEq, Debug, Clone, Copy)]
pub enum HTextAlign {
    Left,
    Center,
    Right,
}

/**
    Text align constant on the vertical axis
*/
#[derive(PartialEq, Debug, Clone, Copy)]
pub enum VTextAlign {
    Top,
    Center,
    Bottom,
}
